test_that("ss_catalog() lists variables with years, data and extras, cached per session", {
  dir <- local_fake_bridge()
  cat <- ss_catalog()
  expect_equal(cat$variable, c("ndi", "walkability", "temis"))
  expect_equal(cat$year_min, c(2012L, 2021L, 2004L))
  expect_equal(cat$year_max, c(2022L, 2021L, 2023L))
  expect_equal(cat$datasets[1], "bg_boundaries, ndi_panel")
  expect_equal(cat$extras[3], "geo, hdf4")
  expect_equal(attr(cat, "data_release"), "2026.07")
  ss_catalog()
  expect_length(fake_requests(dir, "catalog"), 1L)
})

