test_that("ss_doctor() includes data and cache checks", {
  dir <- local_fake_bridge(list(`data-status` = list(missing = list("temis"))))
  withr::local_options(spacescans.data_dir = tempdir())
  out <- NULL
  expect_output(out <- ss_doctor())
  expect_equal(out$status[out$check == "data"], "warn")
  expect_match(out$message[out$check == "data"], "2 of 3")
  expect_true("cache directory" %in% out$check)
  expect_equal(out$status[out$check == "extra hdf4"], "warn")
})

test_that("ss_cache_info() and ss_cache_clear() use the cache root", {
  dir <- local_fake_bridge()
  root <- withr::local_tempdir()
  withr::local_envvar(R_USER_CACHE_DIR = root)
  withr::local_options(spacescans.cache_dir = NULL)
  info <- ss_cache_info()
  expect_s3_class(info, "ss_cache_info")
  expect_equal(info$entries, 2L)
  expect_equal(last_request(dir, "cache-info")$args$cache_dir, file.path(normalizePath(root), "R", "spacescans"))
  expect_output(print(info), "2.0 KB")
  ss_cache_clear(older_than = 2)
  expect_equal(last_request(dir, "cache-clear")$args$older_than_s, 172800)
  ss_cache_clear(older_than = as.difftime(1, units = "hours"))
  expect_equal(last_request(dir, "cache-clear")$args$older_than_s, 3600)
  ss_cache_clear()
  expect_null(last_request(dir, "cache-clear")$args$older_than_s)
  expect_error(ss_cache_clear(older_than = "old"), class = "spacescans_error_config")
})

test_that("ss_custom_raster() validates its arguments and sends years and bands", {
  dir <- local_fake_bridge()
  d <- withr::local_tempdir()
  tifs <- file.path(d, c("a2019.tif", "a2020.tif"))
  file.create(tifs)
  def <- ss_custom_raster(tifs, years = c(2019, 2020), bands = c(1, 2), value_cols = c("x", "y"))
  req <- last_request(dir, "custom-validate")
  expect_equal(req$args$kind, "raster")
  expect_equal(unlist(req$args$options$years), c(2019L, 2020L))
  expect_equal(unlist(req$args$options$bands), c(1L, 2L))
  expect_equal(def$geometry, "raster")
  expect_error(ss_custom_raster(tifs, years = 2019), class = "spacescans_error_config")
  expect_error(ss_custom_raster(file.path(d, "none.tif")), class = "spacescans_error_config")
  expect_error(ss_custom_polygon(tifs[1], boundary = "Tract", key_col = "k"), class = "spacescans_error_config")
})
